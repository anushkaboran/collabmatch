const LABEL: Record<string, string> = { invited: "Waiting", countered: "Asked for more", accepted: "Accepted", declined: "Declined", in_progress: "Making content", submitted: "Posted", completed: "Done" };
export function Tracker({ collabs, budget, onAnswerCounter, onComplete }: {
  collabs: CollaborationView[]; budget: number;
  onAnswerCounter: (c: CollaborationView, pay: boolean) => void; onComplete: (c: CollaborationView) => void;
}) {
  const committed = ["accepted", "in_progress", "submitted", "completed"];
  const agreed = collabs.filter(x => committed.includes(x.status)).reduce((t, x) => t + x.offeredFee, 0);
  const waiting = collabs.filter(x => x.status === "invited" || x.status === "countered").reduce((t, x) => t + (x.status === "countered" ? x.counterFee ?? x.offeredFee : x.offeredFee), 0);
  const yes = collabs.filter(x => committed.includes(x.status)).length;
  const copy = async (url: string) => { try { await navigator.clipboard.writeText(url); return true; } catch { return false; } };
  return (
    <>
      <div className="row between"><h2 id="team-h">Invites sent</h2><span className="pill p-accepted">{yes} of {collabs.length} said yes</span></div>
      <div className="team-stats">
        <div className="ts" style={{ background: "var(--green-soft)", color: "var(--green)" }}><b>${agreed}</b><span>agreed</span></div>
        <div className="ts" style={{ background: "var(--blue-soft)", color: "var(--blue)" }}><b>${waiting}</b><span>waiting</span></div>
        <div className="ts" style={{ background: "var(--violet-soft)", color: "var(--violet)" }}><b>${budget}</b><span>budget</span></div>
      </div>
      {agreed + waiting > budget && <div className="note warn">${agreed + waiting - budget} over if everyone says yes</div>}
      <div>
        {collabs.map(x => {
          const c = x.creator;
          const link = typeof window !== "undefined" ? `${window.location.origin}/invite/${x.inviteToken}` : `/invite/${x.inviteToken}`;
          return (
            <div key={x.id} className="tr"><Avatar creator={c} />
              <div style={{ display: "grid", gap: 8, minWidth: 0 }}>
                <div className="row between"><span className="name">{c.name}</span><span className="money">${x.offeredFee}</span></div>
                <div className="row"><span className={`pill p-${x.status}`}>{LABEL[x.status]}</span>{x.simulated && <span className="tiny">simulated reply</span>}</div>
                {x.status === "countered" && (
                  <div className="note warn" style={{ display: "grid", gap: 8 }}>
                    <span>Wants ${x.counterFee}{x.counterNote ? ` · "${x.counterNote}"` : ""}</span>
                    <div className="row"><button type="button" className="btn fill" onClick={() => onAnswerCounter(x, true)}>Pay ${x.counterFee}</button><button type="button" className="btn" onClick={() => onAnswerCounter(x, false)}>Keep ${x.offeredFee}</button></div>
                  </div>
                )}
                {x.status === "submitted" && <button type="button" className="btn fill" style={{ justifySelf: "start" }} onClick={() => onComplete(x)}>Mark as done</button>}
                {!c.claimed && x.status === "invited" && (
                  <div className="copybox"><code>{link}</code><button type="button" className="btn" onClick={async e => { const ok = await copy(link); (e.target as HTMLButtonElement).textContent = ok ? "Copied" : "Select to copy"; }}>Copy link</button></div>
                )}
              </div>
            </div>
          );
        })}
      </div>
      {collabs.some(x => x.creatorId === "maya" && x.status === "invited") && <div className="note info">Tap <b>I&apos;m a creator</b> to answer as Maya</div>}
    </>
  );
}

