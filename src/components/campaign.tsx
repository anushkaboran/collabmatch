/* ---------- campaign strip: title, budget slider, editable chips ---------- */
export function BriefStrip({ brief, source, onBudget, onChips }: {
  brief: CampaignBrief;
  source?: "gemini" | "heuristic";
  onBudget: (v: number) => void;
  onChips: (field: "audienceTags" | "niches" | "platforms", values: string[]) => void;
}) {
  const [budget, setBudget] = useState(brief.budget);
  const [prev, setPrev] = useState(brief.budget);
  if (prev !== brief.budget) { setPrev(brief.budget); setBudget(brief.budget); }
  const group = (field: "audienceTags" | "niches" | "platforms", cls: string, vocab: string[], label: string, show = (v: string) => v) => {
    const vals = brief[field] as string[];
    const left = vocab.filter(v => !vals.includes(v));
    return (
      <>
        {vals.map(v => (
          <span key={v} className={`chip ${cls}`}>{show(v)}
            <button type="button" aria-label={`Remove ${show(v)}`} onClick={() => onChips(field, vals.filter(x => x !== v))}>×</button>
          </span>
        ))}
        {left.length > 0 && (
          <select className="addsel" aria-label={`Add ${label}`} value="" onChange={e => e.target.value && onChips(field, [...vals, e.target.value])}>
            <option value="">+ {label}</option>
            {left.map(v => <option key={v} value={v}>{show(v)}</option>)}
          </select>
        )}
      </>
    );
  };
  return (
    <section className="brief" aria-label="Campaign">
      <div className="brief-top">
        <div style={{ display: "grid", gap: 6 }}><h2>{brief.title}</h2>{source && <span className={`chip solo ${source === "gemini" ? "t-v" : ""}`} style={{ justifySelf: "start", ...(source === "gemini" ? {} : { background: "var(--sunk)", color: "var(--muted)" }) }}>{source === "gemini" ? "✦ Generated by Gemini" : "Quick parse"}</span>}</div>
        <div className="budget-ctl">
          <output htmlFor="budget">${budget}</output>
          <input type="range" id="budget" min={50} max={1000} step={10} value={budget} aria-label="Budget in dollars"
            onChange={e => setBudget(Number(e.target.value))}
            onPointerUp={() => budget !== brief.budget && onBudget(budget)}
            onKeyUp={() => budget !== brief.budget && onBudget(budget)} />
        </div>
      </div>
      <div className="groups">
        <span className="chip solo t-place"><Icon name="pin" size={15} />{brief.location}</span>
        {group("audienceTags", "t-aud", AUDIENCES, "audience")}
        {group("niches", "t-niche", NICHES, "topic")}
        {group("platforms", "t-plat", PLATFORMS, "app", platformName)}
      </div>
    </section>
  );
}

/* ---------- team panel ---------- */
export function teamStats(ids: string[], byId: (id: string) => Creator | undefined, matchOf: (id: string) => CreatorMatch | undefined) {
  const cs = ids.map(byId).filter(Boolean) as Creator[];
  const hoods = new Set(cs.map(c => c.hood)).size;
  let ov = 0, pairs = 0;
  for (let i = 0; i < cs.length; i++) for (let j = i + 1; j < cs.length; j++) {
    const A = new Set([...cs[i].audienceTags, cs[i].hood]), B = new Set([...cs[j].audienceTags, cs[j].hood]);
    ov += [...A].filter(x => B.has(x)).length / new Set([...A, ...B]).size; pairs++;
  }
  const reach = Math.round(cs.reduce((t, c) => t + c.followers, 0) * (1 - (pairs ? ov / pairs : 0) * 0.6));
  const fit = cs.length ? Math.round(ids.reduce((t, id) => t + (matchOf(id)?.score ?? 0), 0) / cs.length) : 0;
  const cost = cs.reduce((t, c) => t + c.rate, 0);
  return { hoods, reach, fit, cost, creators: cs };
}

export function TeamPanel({ plans, planIdx, custom, selected, budget, byId, matchOf, busy, onPlan, onInvite, onPreview }: {
  plans: TeamPlan[]; planIdx: number; custom: boolean; selected: string[]; budget: number;
  byId: (id: string) => Creator | undefined; matchOf: (id: string) => CreatorMatch | undefined; busy: boolean;
  onPlan: (i: number) => void; onInvite: () => void; onPreview: () => void;
}) {
  const st = teamStats(selected, byId, matchOf);
  const over = st.cost > budget, scale = Math.max(st.cost, budget, 1);
  return (
    <>
      <h2 id="team-h">Your creator team</h2>
      {plans.length > 0 && (
        <div className="seg-tabs">
          {plans.map((p, i) => <button key={p.id} type="button" aria-pressed={i === planIdx && !custom} onClick={() => onPlan(i)}>{p.label}</button>)}
          {custom && <button type="button" aria-pressed="true">Your picks</button>}
        </div>
      )}
      <div style={{ display: "grid", gap: 12 }}>
        <div className="row between" style={{ alignItems: "flex-end" }}>
          <div className="total">${st.cost} <small>of ${budget}</small></div>
          <span className={`pill ${over ? "p-declined" : st.cost === budget ? "p-accepted" : "p-invited"}`}>{over ? `$${st.cost - budget} over` : st.cost === budget ? "Budget fully used" : `$${budget - st.cost} left`}</span>
        </div>
        <div className="track" role="img" aria-label={`$${st.cost} of $${budget} budget used`}>
          {st.creators.map(c => { const w = (c.rate / scale) * 100; return <div key={c.id} className={`seg ${colorClass(c)}`} style={{ width: `${w}%` }}>{w > 18 && <span className="sav">{initials(c.name)}</span>}<b>${c.rate}</b></div>; })}
        </div>
        <div className="ticks"><span>$0</span><span>${budget}</span></div>
      </div>
      {st.creators.length ? (
        <>
          <div className="faces-row">{st.creators.map(c => <span key={c.id} className="face"><Avatar creator={c} size="sm" />{c.name.split(" ")[0]}</span>)}</div>
          <div className="team-stats">
            <div className="ts" style={{ background: "var(--green-soft)", color: "var(--green)" }}><Icon name="pin" /><b>{st.hoods}</b><span>neighborhood{st.hoods === 1 ? "" : "s"}</span></div>
            <div className="ts" style={{ background: "var(--pink-soft)", color: "var(--pink)" }}><Icon name="people" /><b>~{kfmt(st.reach)}</b><span>people reached</span></div>
            <div className="ts" style={{ background: "var(--violet-soft)", color: "var(--violet)" }}><Icon name="spark" /><b>{st.fit}</b><span>average fit</span></div>
          </div>
        </>
      ) : <p className="muted">Tap + on a creator to add them.</p>}
      {st.creators.some(c => c.rateType === "estimated") && <div className="note warn">Includes estimated rates</div>}
      <button type="button" className="cta" disabled={!st.creators.length || over || busy} onClick={onInvite}>
        {busy ? "Sending…" : over ? "Over budget" : `Invite ${st.creators.length === 1 ? "this creator" : `all ${st.creators.length}`}`}
      </button>
      <button type="button" className="link" style={{ justifySelf: "center" }} disabled={!st.creators.length} onClick={onPreview}>Preview the messages</button>
    </>
  );
}

/* ---------- match card ---------- */
export function MatchCard({ m, brief, picked, locked, onToggle }: { m: CreatorMatch; brief: CampaignBrief; picked: boolean; locked: boolean; onToggle: () => void }) {
  const [open, setOpen] = useState(false);
  const c = m.creator;
  const posts = c.topPosts.slice(0, 2);
  const topAud = c.audienceTags.filter(a => brief.audienceTags.includes(a)).slice(0, 1);
  const topNiche = c.niches.filter(n => brief.niches.includes(n)).slice(0, 2);
  const FC: Record<string, string> = { audience: "pink", niche: "orange", location: "green", budget: "violet", style: "blue", engagement: "pink", platform: "blue" };
  return (
    <article className={`card ${picked ? "picked" : ""} ${m.eligible ? "" : "out"}`}>
      <div className="thumbs">
        {posts.map((p, i) => <div key={p.thumbnailUrl + i} className="t"><Photo src={p.thumbnailUrl} alt={p.caption} />{i === 0 && <span className="play"><Icon name="play" size={10} /></span>}</div>)}
      </div>
      <div className="cbody">
        <div className="chead">
          <div style={{ minWidth: 0, display: "flex", gap: 10, alignItems: "center" }}><Avatar creator={c} /><div style={{ minWidth: 0 }}><div className="name">{c.name}</div><div className="handle">{c.handle}</div></div></div>
          <ScoreRing m={m} />
          {m.eligible && !locked && <button type="button" className="toggle" aria-pressed={picked} aria-label={`${picked ? "Remove" : "Add"} ${c.name}`} onClick={onToggle}>{picked ? "✓" : "+"}</button>}
        </div>
        <div className="row" style={{ gap: 12 }}><span className="price">{c.rateType === "estimated" ? "~" : ""}${c.rate}</span><span className="tiny">{kfmt(c.followers)} followers{c.engagementRate ? ` · ${(c.engagementRate * 100).toFixed(1)}% engage` : ""}</span></div>
        <div className="facts">
          <SourceBadge c={c} />
          <span className="chip solo t-place"><Icon name="pin" size={15} />{c.hood}{c.location !== brief.location ? `, ${c.location}` : ""}</span>
          {topAud.map(a => <span key={a} className="chip solo t-aud">{a}</span>)}
          {topNiche.map(n => <span key={n} className="chip solo t-niche">{n}</span>)}
        </div>
        {!m.eligible && <span className="chip solo" style={{ background: "var(--bad-soft)", color: "var(--bad)", justifySelf: "start" }}>{m.ineligibleReason}</span>}
        <button type="button" className="link" style={{ justifySelf: "start" }} aria-expanded={open} onClick={() => setOpen(!open)}>{open ? "Hide score" : "Why this score?"}</button>
      </div>
      {open && (
        <div className="factors">
          {m.factors.map(f => (
            <div key={f.key} className="factor"><b>{f.label}</b><span className="fb"><i style={{ width: `${Math.max(4, Math.round(f.score * 100))}%`, background: `var(--${FC[f.key]})` }} /></span><span className="ev">{f.evidence}</span></div>
          ))}
        </div>
      )}
    </article>
  );
}

/* ---------- add someone found on social media ---------- */
export function AddFromSocial({ onAdd }: { onAdd: (v: { handle: string; platform: Platform; followers: number; notes: string }) => Promise<void> }) {
  const [handle, setHandle] = useState(""), [followers, setFollowers] = useState(""), [notes, setNotes] = useState("");
  const [err, setErr] = useState(""), [busy, setBusy] = useState(false), [open, setOpen] = useState(false);
  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!handle.trim()) { setErr("Add their handle"); return; }
    setBusy(true); setErr("");
    try { await onAdd({ handle: handle.trim(), platform: "instagram", followers: Number(followers) || 0, notes }); setHandle(""); setFollowers(""); setNotes(""); setOpen(false); }
    catch (x) { setErr((x as Error).message); }
    finally { setBusy(false); }
  }
  return (
    <details className="more" open={open} onToggle={e => setOpen((e.target as HTMLDetailsElement).open)}>
      <summary>+ Add someone you follow on Instagram</summary>
      <form onSubmit={submit} style={{ display: "grid", gap: 12 }}>
        <div className="grid2">
          <label className="f" htmlFor="x-handle">Handle<input type="text" id="x-handle" placeholder="@seattlesnacks" value={handle} onChange={e => setHandle(e.target.value)} /></label>
          <label className="f" htmlFor="x-followers">Followers<input type="number" id="x-followers" placeholder="3000" min={0} value={followers} onChange={e => setFollowers(e.target.value)} /></label>
        </div>
        <label className="f" htmlFor="x-notes">They post about<input type="text" id="x-notes" placeholder="coffee shops, student life" value={notes} onChange={e => setNotes(e.target.value)} /></label>
        <div className="row"><button type="submit" className="btn fill" disabled={busy}>{busy ? "Adding…" : "Add"}</button><span className="tiny">We estimate their rate and give you an invite link</span>{err && <span className="small" style={{ color: "var(--bad)", fontWeight: 800 }}>{err}</span>}</div>
      </form>
    </details>
  );
}

/* ---------- preview modal ---------- */
export function PreviewModal({ creators, drafts, loading, onChange, onClose, onSend }: {
  creators: Creator[]; drafts: Record<string, { fee: number; msg: string }>; loading: boolean;
  onChange: (id: string, d: { fee: number; msg: string }) => void; onClose: () => void; onSend: () => void;
}) {
  return (
    <div className="scrim" onClick={e => e.target === e.currentTarget && onClose()} onKeyDown={e => e.key === "Escape" && onClose()}>
      <div className="modal" role="dialog" aria-modal="true" aria-labelledby="pv-h">
        <div className="row between"><h2 id="pv-h">Your messages</h2><button type="button" className="btn" onClick={onClose}>Close</button></div>
        {loading ? <div style={{ display: "grid", gap: 12 }}>{creators.map(c => <div key={c.id} className="skeleton" style={{ height: 150 }} />)}</div> : creators.map(c => {
          const d = drafts[c.id];
          if (!d) return null;
          return (
            <div key={c.id} style={{ display: "grid", gap: 8 }}>
              <div className="row between"><div className="row"><Avatar creator={c} size="sm" /><span className="name">{c.name}</span></div>
                <label className="row small" htmlFor={`fee-${c.id}`} style={{ gap: 6, fontWeight: 800 }}>$<input type="number" id={`fee-${c.id}`} value={d.fee} style={{ width: 90 }} onChange={e => onChange(c.id, { ...d, fee: Number(e.target.value) })} /></label></div>
              <textarea className="in" id={`msg-${c.id}`} value={d.msg} onChange={e => onChange(c.id, { ...d, msg: e.target.value })} />
              {c.dataSource === "business" && <p className="tiny">{c.handle} isn&apos;t on CollabMatch yet. You&apos;ll get a personal link to send by DM.</p>}
            </div>
          );
        })}
        <button type="button" className="cta" disabled={loading} onClick={onSend}>Send {creators.length} invite{creators.length === 1 ? "" : "s"}</button>
      </div>
    </div>
  );
}

